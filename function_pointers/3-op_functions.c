#include "3-calc.h"
/**
* op_add - adds two ints
* @a: value num1
* @b: value num2
* Return: total
*/
int op_add(int a, int b)
{
	return (a + b);
}

/**
* op_sub - subtracts two ints
** @a: value num1
* @b: value num2
* Return: total
*/

int op_sub(int a, int b)
{
	return (a - b);
}

/**
* op_mul - multiplies two ints
* @a: value num1
* @b: value num2
* Return: total
*/
int op_mul(int a, int b)
{
	return (a * b);
}

/**
* op_div - divides two ints
* @a: value num1
* @b: value num2
* Return: total
*/
int op_div(int a, int b)
{
	return (a / b);
}

/**
* op_mod - finds reminder of two ints.
* @a: value num1
* @b: value num2
* Return: total
*/
int op_mod(int a, int b)
{
	return (a % b);
}

